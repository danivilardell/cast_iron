package auditcircuit

import (
	"math/big"

	"github.com/consensys/gnark/frontend"

	"cast_iron/shared"
)

// PlainBallot is the cleartext registration content of one ballot together
// with its opening proof and record entry.
type PlainBallot struct {
	PkAx, PkAy, PosReg *big.Int
	B3Rx, B3Ry, B3S    *big.Int
	Proof              []*big.Int // π_open fields (nil/zeros = absent)
	RsigHi, RsigLo     *big.Int   // record entry at PosReg
	Path               []*big.Int // sibling path of the record leaf
}

// Fixture is a complete audit instance: public context, ballots, the
// tallier's witness and the expected outputs.
type Fixture struct {
	Cfg               Config
	Sk, G, H          *big.Int
	Eid, VoterRoot    *big.Int
	RecordRoot        *big.Int
	Ballots           []PlainBallot
	TupleHashes       []*big.Int
	Entries           []*big.Int
	Bits              []bool // expected b_i
	Alpha, CReg       *big.Int
	Ciphertexts       []Ballot
	Records           []RecordOpening
	RecordLeaves      []*big.Int // record tree leaves by position
	RecordTotalLeaves int
}

// Encrypt encrypts a field element under the fixture key.
func (f *Fixture) Encrypt(m *big.Int) Ciphertext {
	c1, c2 := shared.ElGamalEncryptScalar(m, f.G, f.H)
	return Ciphertext{C1: c1, C2: c2}
}

// NewFixture builds a fixture for the given cleartext ballots.  Each ballot's
// PosReg selects its leaf in a record tree of recordTotalLeaves entries; the
// tree holds the ballots' entries at their positions (other positions are
// fillers).  Ballots must have distinct PosReg < recordTotalLeaves.  bits[i]
// is the expected b_i; proofs are generated by prover for ballots with
// bits[i] = true and left as given (invalid / absent) otherwise.
func NewFixture(cfg Config, sk, g, h, eid, voterRoot *big.Int, ballots []PlainBallot, recordTotalLeaves int) *Fixture {
	f := &Fixture{Cfg: cfg, Sk: sk, G: g, H: h, Eid: eid, VoterRoot: voterRoot, Ballots: ballots, RecordTotalLeaves: recordTotalLeaves}

	// record tree: leaf at PosReg = EntryCommitment(PosReg, rσ)
	maxPos := 0
	for _, b := range ballots {
		if p := int(b.PosReg.Int64()); p > maxPos {
			maxPos = p
		}
	}
	leaves := make([]*big.Int, maxPos+1)
	for i := range leaves {
		leaves[i] = shared.PoseidonMD(big.NewInt(0), big.NewInt(int64(i)), big.NewInt(0)) // filler, as BuildPlainMerkle
	}
	for _, b := range ballots {
		leaves[b.PosReg.Int64()] = shared.EntryCommitmentNative(b.PosReg, b.RsigHi, b.RsigLo)
	}
	root, paths := shared.BuildPlainMerkle(leaves, recordTotalLeaves)
	f.RecordRoot = root
	f.RecordLeaves = leaves
	for i, b := range ballots {
		if b.Path == nil {
			ballots[i].Path = paths[b.PosReg.Int64()]
		}
	}

	f.Alpha = shared.CRegAlphaNative(eid, voterRoot, root)
	f.Refresh()
	return f
}

// Refresh recomputes the tuple hashes, entry commitments, ciphertexts, witness
// and expected outputs from the current cleartext ballots (call after editing
// Ballots).  The record tree itself is not rebuilt: it is the public record.
func (f *Fixture) Refresh() {
	n := len(f.Ballots)
	f.TupleHashes = make([]*big.Int, n)
	f.Entries = make([]*big.Int, n)
	f.Ciphertexts = make([]Ballot, n)
	f.Records = make([]RecordOpening, n)
	f.Bits = make([]bool, n)
	for i, b := range f.Ballots {
		hB3 := shared.HashB3Native(b.B3Rx, b.B3Ry, b.B3S)
		f.TupleHashes[i] = shared.RegTupleHashNative(b.PkAx, b.PkAy, b.PosReg, hB3)
		f.Entries[i] = shared.EntryCommitmentNative(b.PosReg, b.RsigHi, b.RsigLo)
		ct := Ballot{
			PkAnchorX_C: f.Encrypt(b.PkAx), PkAnchorY_C: f.Encrypt(b.PkAy), PosRegC: f.Encrypt(b.PosReg),
			B3_RX_C: f.Encrypt(b.B3Rx), B3_RY_C: f.Encrypt(b.B3Ry), B3_S_C: f.Encrypt(b.B3S),
			ProofC: make([]Ciphertext, f.Cfg.ProofFields),
		}
		for j := 0; j < f.Cfg.ProofFields; j++ {
			v := big.NewInt(0)
			if j < len(b.Proof) && b.Proof[j] != nil {
				v = b.Proof[j]
			}
			ct.ProofC[j] = f.Encrypt(v)
		}
		f.Ciphertexts[i] = ct
		path := make([]frontend.Variable, f.Cfg.RecordDepth)
		for k := range path {
			path[k] = b.Path[k]
		}
		f.Records[i] = RecordOpening{RsigHi: b.RsigHi, RsigLo: b.RsigLo, Path: path}
		f.Bits[i] = f.expectedBit(i)
	}
	f.CReg = shared.ComputeCReg(f.Alpha, f.TupleHashes, f.Bits)
}

// expectedBit mirrors the circuit's b_i natively.
func (f *Fixture) expectedBit(i int) bool {
	b := f.Ballots[i]
	if b.PosReg.Sign() < 0 || b.PosReg.BitLen() > f.Cfg.RecordDepth {
		return false
	}
	// Merkle membership
	idx := b.PosReg.Int64()
	node := new(big.Int).Set(shared.EntryCommitmentNative(b.PosReg, b.RsigHi, b.RsigLo))
	for k := 0; k < f.Cfg.RecordDepth; k++ {
		if (idx>>uint(k))&1 == 1 {
			node = shared.PoseidonMD(b.Path[k], node)
		} else {
			node = shared.PoseidonMD(node, b.Path[k])
		}
	}
	if node.Cmp(f.RecordRoot) != 0 {
		return false
	}
	if f.Cfg.Verifier == nil {
		return true
	}
	switch v := f.Cfg.Verifier.(type) {
	case MockVerifier:
		if len(b.Proof) != v.Fields {
			return false
		}
		vals := append([]*big.Int{big.NewInt(MockDomainTag), f.TupleHashes[i], f.Entries[i]}, b.Proof[:v.Fields-1]...)
		return shared.PoseidonMD(vals...).Cmp(b.Proof[v.Fields-1]) == 0
	case ConstVerifier:
		return v.Bit == 1
	}
	panic("unknown verifier type")
}

// Assignment returns the full witness (with CReg = the expected value).
func (f *Fixture) Assignment() *Circuit {
	return &Circuit{
		ElectionID: f.Eid, VoterRollRoot: f.VoterRoot, RecordRoot: f.RecordRoot,
		ElGamalG: f.G, ElGamalH: f.H, CReg: f.CReg,
		BulletinBoard: f.Ciphertexts, ElGamalSk: f.Sk, Records: f.Records,
	}
}

// Skeleton returns the compilable circuit for this fixture.
func (f *Fixture) Skeleton() *Circuit { return NewCircuit(f.Cfg, len(f.Ballots)) }

// RandomBallot returns a random honest ballot at position pos with a valid
// proof from the configured verifier (if it is a MockVerifier).
func RandomBallot(cfg Config, pos int) PlainBallot {
	b := PlainBallot{
		PkAx: shared.RandomScalar(), PkAy: shared.RandomScalar(), PosReg: big.NewInt(int64(pos)),
		B3Rx: shared.RandomScalar(), B3Ry: shared.RandomScalar(), B3S: shared.RandomScalar(),
		RsigHi: new(big.Int).Rsh(shared.RandomScalar(), 128), RsigLo: new(big.Int).Rsh(shared.RandomScalar(), 128),
	}
	return b
}

// RandomFixture builds an honest fixture with n ballots at positions 0..n-1.
func RandomFixture(cfg Config, n, recordTotalLeaves int) *Fixture {
	sk, g, h := shared.ElGamalKeygen()
	ballots := make([]PlainBallot, n)
	for i := range ballots {
		ballots[i] = RandomBallot(cfg, i)
	}
	f := NewFixture(cfg, sk, g, h, shared.RandomScalar(), shared.RandomScalar(), ballots, recordTotalLeaves)
	if mv, ok := cfg.Verifier.(MockVerifier); ok {
		for i := range f.Ballots {
			f.Ballots[i].Proof = mv.MockProve(f.TupleHashes[i], f.Entries[i])
		}
		f.Refresh()
	}
	return f
}
